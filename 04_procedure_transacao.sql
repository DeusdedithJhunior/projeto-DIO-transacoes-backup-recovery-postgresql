-- =====================================================================
-- 04_procedure_transacao.sql
-- PARTE 2 – Transação dentro de procedure (PL/pgSQL, schema ecommerce)
-- PostgreSQL 14+
--
-- Cria:
--   - tabela ecommerce.log_pedido       (histórico de status dos pedidos)
--   - função  ecommerce.fn_log_pedido() + trigger trg_log_pedido
--   - procedure ecommerce.sp_finalizar_pedido(...)
-- Pode ser reexecutado (IF NOT EXISTS / CREATE OR REPLACE).
--
-- ---------------------------------------------------------------------
-- REGRAS DE TRANSAÇÃO EM PL/pgSQL
-- ---------------------------------------------------------------------
-- 1) PL/pgSQL não aceita SAVEPOINT / ROLLBACK TO SAVEPOINT explícitos.
--    O equivalente é o bloco aninhado BEGIN ... EXCEPTION ... END:
--    ao entrar no bloco o PostgreSQL cria um savepoint implícito; se
--    ocorrer erro, tudo o que foi feito DENTRO do bloco é desfeito e a
--    execução continua no tratador EXCEPTION, preservando o que veio
--    antes. É assim que se faz o "rollback parcial".
--
-- 2) COMMIT e ROLLBACK podem ser usados dentro de PROCEDURE (não em
--    FUNCTION), mas só funcionam quando o CALL é executado fora de um
--    bloco de transação. Se o CALL estiver dentro de BEGIN ... COMMIT,
--    ou o cliente estiver em modo "Manual Commit" (DBeaver) ou com
--    \set AUTOCOMMIT off (psql), o erro é:
--        ERROR: invalid transaction termination
--    Por isso execute o CALL em modo autocommit.
--
-- 3) COMMIT/ROLLBACK não podem ser executados dentro de um bloco que
--    tenha EXCEPTION (nem dentro do próprio tratador), porque ali existe
--    um savepoint implícito ativo. Na procedure abaixo o COMMIT e o
--    ROLLBACK ficam no corpo principal, que não tem EXCEPTION.
--
-- 4) Após um COMMIT ou ROLLBACK dentro da procedure, uma nova transação
--    começa automaticamente; variáveis locais mantêm seus valores.
--
-- 5) Erros não previstos (não tratados) interrompem o CALL, e o
--    PostgreSQL desfaz automaticamente tudo o que ainda não foi
--    confirmado: também é um rollback total.
-- =====================================================================

SET search_path TO ecommerce;

-- ---------------------------------------------------------------------
-- Tabela de log (sem FK para pedido, para não depender dele)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS log_pedido (
    id_log          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido       INT          NOT NULL,
    operacao        VARCHAR(30)  NOT NULL,
    status_anterior VARCHAR(20),
    status_novo     VARCHAR(20),
    detalhe         VARCHAR(255),
    data_log        TIMESTAMP    NOT NULL DEFAULT clock_timestamp(),
    usuario         VARCHAR(63)  NOT NULL DEFAULT current_user
);

-- ---------------------------------------------------------------------
-- Trigger: registra inclusão de pedido e mudança de status
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_log_pedido()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO ecommerce.log_pedido (id_pedido, operacao, status_novo)
        VALUES (NEW.id_pedido, 'INSERT', NEW.status);
    ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO ecommerce.log_pedido (id_pedido, operacao, status_anterior, status_novo)
        VALUES (NEW.id_pedido, 'UPDATE STATUS', OLD.status, NEW.status);
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER trg_log_pedido
AFTER INSERT OR UPDATE OF status ON pedido
FOR EACH ROW
EXECUTE FUNCTION fn_log_pedido();

-- ---------------------------------------------------------------------
-- Procedure: finalizar pedido
--
-- Parâmetros:
--   p_id_cliente  cliente que está comprando
--   p_itens       JSONB com os itens, ex.:
--                 '[{"id_produto": 5, "quantidade": 2}]'
--   p_id_forma    forma de pagamento (deve pertencer ao cliente e estar ativa)
--   p_id_local    local de estoque de onde sai a mercadoria
--   p_frete       valor do frete
--   p_id_pedido   (INOUT) id do pedido gravado, ou NULL se nada foi gravado
--   p_resultado   (INOUT) SUCESSO | ROLLBACK TOTAL | ROLLBACK PARCIAL
--   p_mensagem    (INOUT) mensagem explicando o resultado
--
-- Etapas:
--   1. Validações iniciais (cliente e lista de itens)
--   2. Insere o pedido
--   3. Para cada item: trava e valida o estoque, insere o item e baixa
--      o estoque. Estoque insuficiente ou produto inexistente
--      → ROLLBACK TOTAL (desfaz pedido e itens já inseridos)
--   4. Registra o pagamento e confirma o pedido num bloco aninhado
--      BEGIN ... EXCEPTION (savepoint implícito). Se falhar
--      → ROLLBACK PARCIAL: só o pagamento é desfeito; o pedido fica
--        "Em processamento" com itens e estoque reservados
--   5. COMMIT
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_finalizar_pedido(
    p_id_cliente  INT,
    p_itens       JSONB,
    p_id_forma    INT,
    p_id_local    INT,
    p_frete       NUMERIC(10,2) DEFAULT 0,
    INOUT p_id_pedido INT  DEFAULT NULL,
    INOUT p_resultado TEXT DEFAULT NULL,
    INOUT p_mensagem  TEXT DEFAULT NULL
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_item        RECORD;
    v_estoque     INT;
    v_valor       NUMERIC(10,2);
    v_total       NUMERIC(10,2) := 0;
    v_forma_ok    BOOLEAN;
BEGIN
    p_id_pedido := NULL;

    -- 1. Validações iniciais (nada foi gravado ainda)
    IF NOT EXISTS (SELECT 1 FROM ecommerce.cliente WHERE id_cliente = p_id_cliente) THEN
        p_resultado := 'ROLLBACK TOTAL';
        p_mensagem  := format('Cliente %s não existe. Nada foi gravado.', p_id_cliente);
        ROLLBACK;
        RAISE NOTICE '%', p_mensagem;
        RETURN;
    END IF;

    IF p_itens IS NULL OR jsonb_typeof(p_itens) <> 'array' OR jsonb_array_length(p_itens) = 0 THEN
        p_resultado := 'ROLLBACK TOTAL';
        p_mensagem  := 'Lista de itens vazia ou inválida. Nada foi gravado.';
        ROLLBACK;
        RAISE NOTICE '%', p_mensagem;
        RETURN;
    END IF;

    -- 2. Insere o pedido
    INSERT INTO ecommerce.pedido (id_cliente, status, descricao, frete)
    VALUES (p_id_cliente, 'Em processamento', 'Pedido via sp_finalizar_pedido', p_frete)
    RETURNING id_pedido INTO p_id_pedido;

    -- 3. Itens: valida estoque, insere item e baixa estoque
    FOR v_item IN
        SELECT (x ->> 'id_produto')::INT AS id_produto,
               (x ->> 'quantidade')::INT AS quantidade
        FROM jsonb_array_elements(p_itens) AS x
    LOOP
        SELECT valor INTO v_valor
        FROM ecommerce.produto
        WHERE id_produto = v_item.id_produto;

        -- FOR UPDATE trava a linha do estoque até o fim da transação,
        -- evitando que outra sessão venda a mesma unidade ao mesmo tempo
        SELECT quantidade INTO v_estoque
        FROM ecommerce.estoque
        WHERE id_produto = v_item.id_produto
          AND id_local   = p_id_local
        FOR UPDATE;

        IF v_valor IS NULL OR v_estoque IS NULL OR v_item.quantidade IS NULL
           OR v_item.quantidade <= 0 OR v_estoque < v_item.quantidade THEN
            p_mensagem := CASE
                WHEN v_valor IS NULL THEN
                    format('Produto %s não existe.', v_item.id_produto)
                WHEN v_item.quantidade IS NULL OR v_item.quantidade <= 0 THEN
                    format('Quantidade inválida para o produto %s.', v_item.id_produto)
                ELSE
                    format('Estoque insuficiente do produto %s no local %s: pedido %s, disponível %s.',
                           v_item.id_produto, p_id_local, v_item.quantidade, COALESCE(v_estoque, 0))
                END
                || format(' Pedido %s desfeito, nada foi gravado.', p_id_pedido);

            ROLLBACK;                       -- ROLLBACK TOTAL: desfaz pedido, itens e baixas
            p_id_pedido := NULL;
            p_resultado := 'ROLLBACK TOTAL';
            RAISE NOTICE '%', p_mensagem;
            RETURN;
        END IF;

        INSERT INTO ecommerce.item_pedido (id_pedido, id_produto, quantidade, valor_unitario)
        VALUES (p_id_pedido, v_item.id_produto, v_item.quantidade, v_valor);

        UPDATE ecommerce.estoque
           SET quantidade = quantidade - v_item.quantidade
         WHERE id_produto = v_item.id_produto
           AND id_local   = p_id_local;

        v_total := v_total + v_valor * v_item.quantidade;
    END LOOP;

    v_total := v_total + COALESCE(p_frete, 0);

    -- 4. Pagamento (etapa secundária) – bloco aninhado = savepoint implícito
    BEGIN
        SELECT TRUE INTO v_forma_ok
        FROM ecommerce.forma_pagamento
        WHERE id_forma = p_id_forma
          AND id_cliente = p_id_cliente
          AND ativo;

        INSERT INTO ecommerce.pagamento (id_pedido, id_forma, valor, status, data_pagamento)
        VALUES (p_id_pedido, p_id_forma, v_total, 'Aprovado', clock_timestamp());

        -- A trigger registra esta mudança de status no log
        UPDATE ecommerce.pedido SET status = 'Confirmado' WHERE id_pedido = p_id_pedido;

        -- Validação feita depois dos comandos de propósito: ao falhar,
        -- mostra que o INSERT do pagamento, o UPDATE e o log gerado
        -- pela trigger são todos desfeitos juntos.
        IF v_forma_ok IS NULL THEN
            RAISE EXCEPTION 'Forma de pagamento % inválida, inativa ou de outro cliente', p_id_forma;
        END IF;

        p_resultado := 'SUCESSO';
        p_mensagem  := format('Pedido %s confirmado. Total R$ %s pago com a forma %s.',
                              p_id_pedido, v_total, p_id_forma);
    EXCEPTION
        WHEN OTHERS THEN
            -- ROLLBACK PARCIAL: só o que foi feito dentro deste bloco foi
            -- desfeito. Pedido, itens e baixa de estoque continuam valendo.
            INSERT INTO ecommerce.log_pedido (id_pedido, operacao, detalhe)
            VALUES (p_id_pedido, 'PAGAMENTO FALHOU', left(SQLERRM, 255));

            p_resultado := 'ROLLBACK PARCIAL';
            p_mensagem  := format('Pedido %s gravado como "Em processamento", mas o pagamento não foi registrado: %s',
                                  p_id_pedido, SQLERRM);
    END;

    -- 5. Confirma tudo o que restou (fora de bloco com EXCEPTION)
    COMMIT;
    RAISE NOTICE '%', p_mensagem;
END;
$$;

-- Conferência: objetos criados
SELECT n.nspname AS schema, p.proname AS nome,
       CASE p.prokind WHEN 'p' THEN 'procedure' WHEN 'f' THEN 'function' END AS tipo
FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname = 'ecommerce'
ORDER BY tipo, nome;

SELECT tgname AS trigger, tgrelid::regclass AS tabela
FROM pg_trigger
WHERE NOT tgisinternal AND tgrelid = 'ecommerce.pedido'::regclass;
