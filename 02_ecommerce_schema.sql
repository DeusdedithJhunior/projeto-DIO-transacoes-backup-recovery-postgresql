-- =====================================================================
-- 02_ecommerce_schema.sql
-- Banco E-COMMERCE (cenário do curso DIO) criado no schema "ecommerce".
-- PostgreSQL 14+
--
-- Atenção: o script recria o schema do zero (DROP ... CASCADE), o que
-- também remove índices e procedures criados pelos scripts 04 e 06.
-- =====================================================================

DROP SCHEMA IF EXISTS ecommerce CASCADE;
CREATE SCHEMA ecommerce;
SET search_path TO ecommerce;

-- ---------------------------------------------------------------------
-- Cliente: pessoa física (CPF) ou jurídica (CNPJ), nunca os dois.
-- A regra é garantida pela CHECK chk_cliente_pf_pj.
-- ---------------------------------------------------------------------
CREATE TABLE cliente (
    id_cliente      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo            CHAR(2)        NOT NULL CHECK (tipo IN ('PF', 'PJ')),
    nome            VARCHAR(100)   NOT NULL,   -- nome completo ou razão social
    cpf             CHAR(11)       UNIQUE,
    cnpj            CHAR(14)       UNIQUE,
    email           VARCHAR(100)   NOT NULL UNIQUE,
    telefone        VARCHAR(15),
    endereco        VARCHAR(150),
    cidade          VARCHAR(50),
    uf              CHAR(2),
    data_cadastro   DATE           NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT chk_cliente_pf_pj CHECK (
        (tipo = 'PF' AND cpf  IS NOT NULL AND cnpj IS NULL) OR
        (tipo = 'PJ' AND cnpj IS NOT NULL AND cpf  IS NULL)
    ),
    CONSTRAINT chk_cliente_cpf  CHECK (cpf  ~ '^[0-9]{11}$'),
    CONSTRAINT chk_cliente_cnpj CHECK (cnpj ~ '^[0-9]{14}$')
);

CREATE TABLE categoria (
    id_categoria    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(50)    NOT NULL UNIQUE
);

CREATE TABLE produto (
    id_produto      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100)   NOT NULL,
    id_categoria    INT            NOT NULL,
    descricao       VARCHAR(255),
    valor           NUMERIC(10,2)  NOT NULL CHECK (valor > 0),
    avaliacao       NUMERIC(2,1)   CHECK (avaliacao BETWEEN 0 AND 5),
    para_criancas   BOOLEAN        NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_produto_categoria
        FOREIGN KEY (id_categoria) REFERENCES categoria (id_categoria)
);

CREATE TABLE fornecedor (
    id_fornecedor   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razao_social    VARCHAR(100)   NOT NULL,
    cnpj            CHAR(14)       NOT NULL UNIQUE CHECK (cnpj ~ '^[0-9]{14}$'),
    contato         VARCHAR(15)
);

-- Produtos fornecidos por cada fornecedor (N:M)
CREATE TABLE produto_fornecedor (
    id_fornecedor   INT  NOT NULL REFERENCES fornecedor (id_fornecedor),
    id_produto      INT  NOT NULL REFERENCES produto (id_produto) ON DELETE CASCADE,
    quantidade      INT  NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
    PRIMARY KEY (id_fornecedor, id_produto)
);

-- Vendedor terceiro (marketplace): PF ou PJ, nunca os dois
CREATE TABLE vendedor_terceiro (
    id_vendedor     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razao_social    VARCHAR(100)   NOT NULL,
    nome_fantasia   VARCHAR(100),
    cnpj            CHAR(14)       UNIQUE,
    cpf             CHAR(11)       UNIQUE,
    cidade          VARCHAR(50),
    uf              CHAR(2),
    CONSTRAINT chk_vendedor_pf_pj CHECK (
        (cnpj IS NOT NULL AND cpf IS NULL) OR (cpf IS NOT NULL AND cnpj IS NULL)
    )
);

-- Produtos ofertados por vendedores terceiros (N:M)
CREATE TABLE produto_vendedor (
    id_vendedor     INT  NOT NULL REFERENCES vendedor_terceiro (id_vendedor),
    id_produto      INT  NOT NULL REFERENCES produto (id_produto) ON DELETE CASCADE,
    quantidade      INT  NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
    PRIMARY KEY (id_vendedor, id_produto)
);

CREATE TABLE local_estoque (
    id_local        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(50)    NOT NULL UNIQUE,
    cidade          VARCHAR(50)    NOT NULL,
    uf              CHAR(2)        NOT NULL
);

-- Quantidade de cada produto em cada local de estoque
CREATE TABLE estoque (
    id_produto      INT  NOT NULL REFERENCES produto (id_produto) ON DELETE CASCADE,
    id_local        INT  NOT NULL REFERENCES local_estoque (id_local),
    quantidade      INT  NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
    PRIMARY KEY (id_produto, id_local)
);

CREATE TABLE pedido (
    id_pedido       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente      INT            NOT NULL,
    data_pedido     TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status          VARCHAR(20)    NOT NULL DEFAULT 'Em processamento'
                    CHECK (status IN ('Em processamento', 'Confirmado', 'Cancelado', 'Concluído')),
    descricao       VARCHAR(255),
    frete           NUMERIC(10,2)  NOT NULL DEFAULT 0 CHECK (frete >= 0),
    CONSTRAINT fk_pedido_cliente
        FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
);

CREATE TABLE item_pedido (
    id_pedido       INT            NOT NULL REFERENCES pedido (id_pedido) ON DELETE CASCADE,
    id_produto      INT            NOT NULL REFERENCES produto (id_produto),
    quantidade      INT            NOT NULL CHECK (quantidade > 0),
    valor_unitario  NUMERIC(10,2)  NOT NULL CHECK (valor_unitario > 0),
    PRIMARY KEY (id_pedido, id_produto)
);

-- Formas de pagamento cadastradas pelo cliente (um cliente pode ter várias).
-- Por segurança, guarda-se apenas os 4 últimos dígitos do cartão.
CREATE TABLE forma_pagamento (
    id_forma        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente      INT            NOT NULL REFERENCES cliente (id_cliente) ON DELETE CASCADE,
    tipo            VARCHAR(20)    NOT NULL
                    CHECK (tipo IN ('Cartão de crédito', 'Cartão de débito', 'Pix', 'Boleto')),
    bandeira        VARCHAR(20),
    final_cartao    CHAR(4),
    ativo           BOOLEAN        NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_forma_cartao CHECK (
        (tipo LIKE 'Cartão%' AND final_cartao ~ '^[0-9]{4}$') OR
        (tipo NOT LIKE 'Cartão%' AND final_cartao IS NULL)
    )
);

-- Pagamentos de um pedido (um pedido pode ser pago com mais de uma forma)
CREATE TABLE pagamento (
    id_pagamento    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido       INT            NOT NULL REFERENCES pedido (id_pedido) ON DELETE CASCADE,
    id_forma        INT            NOT NULL REFERENCES forma_pagamento (id_forma),
    valor           NUMERIC(10,2)  NOT NULL CHECK (valor > 0),
    status          VARCHAR(15)    NOT NULL DEFAULT 'Pendente'
                    CHECK (status IN ('Pendente', 'Aprovado', 'Recusado', 'Estornado')),
    data_pagamento  TIMESTAMP
);

-- Entrega: uma por pedido, com status e código de rastreio único
CREATE TABLE entrega (
    id_entrega      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido       INT            NOT NULL UNIQUE REFERENCES pedido (id_pedido) ON DELETE CASCADE,
    status          VARCHAR(20)    NOT NULL DEFAULT 'Aguardando envio'
                    CHECK (status IN ('Aguardando envio', 'Em transporte', 'Entregue', 'Devolvido', 'Cancelada')),
    codigo_rastreio VARCHAR(20)    UNIQUE,
    transportadora  VARCHAR(50),
    data_envio      DATE,
    data_entrega    DATE,
    CONSTRAINT chk_entrega_datas CHECK (data_entrega IS NULL OR data_entrega >= data_envio),
    CONSTRAINT chk_entrega_rastreio CHECK (status = 'Aguardando envio' OR status = 'Cancelada' OR codigo_rastreio IS NOT NULL)
);

